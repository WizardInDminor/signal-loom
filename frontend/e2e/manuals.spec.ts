import { expect, test, type Page } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";

// Session 3f: device manuals and the MIDI command library. A guitarist uploads the pedal's own
// manual once, writes down the two or three commands they use (citing the page), marks favorites,
// and picks them by name in the Scene editor; the compiled plan shows the exact bytes, and a later
// edit of the command never changes a saved scene silently.

const MANUAL = path.join(__dirname, "fixtures", "manual.pdf"); // synthetic, generated by tests/support/pdf.py
const PHOTO = path.join(__dirname, "fixtures", "pedal-photo.jpg");
const created: string[] = [];
const createdProfiles: string[] = [];

async function sunsetCopy(page: Page) {
  const sunset = await (await page.request.get("/api/catalog/devices/strymon-sunset")).json();
  const id = `e2e-sunset-${Date.now().toString(36)}`;
  const copy = { ...sunset, id, manufacturer: "E2E", model: `Drive ${id}`, builtin: false, provenance: { ...sunset.provenance, source: "user", evidence: "user" } };
  delete copy.unknown_attributes; delete copy.source; delete copy.document_files;
  expect((await page.request.post("/api/catalog/devices", { data: copy })).ok()).toBeTruthy();
  createdProfiles.push(id);
  return id;
}

async function attachManual(page: Page, profileId: string, title: string) {
  const r = await page.request.post(`/api/catalog/devices/${profileId}/documents`, {
    multipart: { title, kind: "manual", file: { name: "manual.pdf", mimeType: "application/pdf", buffer: fs.readFileSync(MANUAL) } },
  });
  expect(r.ok()).toBeTruthy();
  return (await r.json()).documents[0].document_id as string;
}

/** A copy of the demo rig whose Sunset uses the given profile copy, so the demo library is never changed. */
async function rigWith(page: Page, profileId: string) {
  const list = await (await page.request.get("/api/rigs")).json();
  const src = list.find((r: { name: string }) => r.name.startsWith("Demo rig"));
  const exported = await (await page.request.get(`/api/rigs/${src.id}/export`)).json();
  exported.profiles = exported.profiles.filter((p: { id: string }) => p.id !== "strymon-sunset");
  for (const i of exported.rig.instances) if (i.profile_id === "strymon-sunset") i.profile_id = profileId;
  const res = await page.request.post(`/api/rigs/import?name=${encodeURIComponent(`E2E manuals ${Date.now()}`)}`, { data: exported });
  expect(res.ok()).toBeTruthy();
  const rig = (await res.json()).rig;
  created.push(rig.id);
  return rig.id as string;
}

async function openProfile(page: Page, profileId: string) {
  await page.goto("/catalog");
  await page.getByLabel("Search devices").fill(profileId);
  await page.getByRole("button", { name: new RegExp(profileId) }).click();
  await expect(page.getByTestId("commands-section")).toBeVisible();
}

test.afterEach(async ({ page }) => {
  while (created.length) await page.request.delete(`/api/rigs/${created.pop()}`);
  while (createdProfiles.length) await page.request.delete(`/api/catalog/devices/${createdProfiles.pop()}`);
  await page.request.delete("/api/documents/unreferenced");
});

test("manuals: upload a PDF to a profile, see its pages and find text, reject a non-PDF, rename and detach without harming the profile", async ({ page, context }) => {
  const profileId = await sunsetCopy(page);
  await openProfile(page, profileId);
  const docs = page.getByTestId("documents-section");
  await docs.getByLabel("Document title").fill("Sunset manual");
  await docs.getByTestId("document-file").setInputFiles(MANUAL);
  const row = docs.locator("[data-testid^=document-doc_]");
  await expect(row).toContainText("Sunset manual");
  await expect(row).toContainText("3 pages");
  // A photograph renamed .pdf is refused by content; the profile keeps exactly one document.
  await docs.getByTestId("document-file").setInputFiles({ name: "manual.pdf", mimeType: "application/pdf", buffer: fs.readFileSync(PHOTO) });
  await expect(docs.getByTestId("documents-error")).toContainText("not a PDF");
  await expect(row).toHaveCount(1);
  // View: pages are pictures; search finds the MIDI chart page and jumps to it.
  const [viewer] = await Promise.all([context.waitForEvent("page"), row.getByTestId("document-view").click()]);
  await viewer.waitForLoadState();
  const img = viewer.getByTestId("document-page");
  await expect(img).toHaveAttribute("data-page", "1");
  await expect.poll(async () => img.evaluate((el) => (el as HTMLImageElement).naturalWidth), { timeout: 15_000 }).toBeGreaterThan(100);
  await viewer.getByLabel("Search text").fill("CC 10");
  await viewer.getByRole("button", { name: "Find" }).click();
  const hits = viewer.getByTestId("document-hits");
  await expect(hits).toContainText("p. 2");
  await hits.getByRole("button").first().click();
  await expect(img).toHaveAttribute("data-page", "2");
  await expect(viewer).toHaveURL(/page=2/);
  await expect.poll(async () => img.evaluate((el) => (el as HTMLImageElement).complete && (el as HTMLImageElement).naturalWidth), { timeout: 15_000 }).toBeGreaterThan(100);
  await viewer.screenshot({ path: "test-results/manual-viewer.png", fullPage: true }).catch(() => undefined);
  // The raw file is only a download (never rendered inline by the browser's PDF engine).
  const dl = await viewer.request.get(`/api/documents/${(await row.getAttribute("data-testid"))!.replace("document-", "")}/file`);
  expect(dl.headers()["content-disposition"]).toMatch(/^attachment/);
  expect(dl.headers()["x-content-type-options"]).toBe("nosniff");
  await viewer.close();
  // Rename (title only) and detach without deleting; the profile's other data is untouched.
  page.once("dialog", (d) => d.accept("Sunset owner's manual"));
  await row.getByRole("button", { name: "Rename" }).click();
  await expect(row).toContainText("Sunset owner's manual");
  page.once("dialog", (d) => d.dismiss()); // detach only; keep the file
  await row.getByRole("button", { name: /Detach/ }).click();
  await expect(row).toHaveCount(0);
  const prof = await (await page.request.get(`/api/catalog/devices/${profileId}`)).json();
  expect(prof.documents).toEqual([]);
  expect(prof.midi.cc_map.length).toBe(3);
  const stored = await (await page.request.get("/api/documents")).json();
  expect(stored.some((d: { referenced_by: string[] }) => d.referenced_by.length === 0)).toBeTruthy();
});

test("commands: define a favorite with a manual citation, pick it by name in a scene, inspect the exact bytes, reload, and review after the definition changes", async ({ page }) => {
  const profileId = await sunsetCopy(page);
  const docId = await attachManual(page, profileId, "Sunset manual");
  const rigId = await rigWith(page, profileId);

  // --- Device library: write the command down once.
  await openProfile(page, profileId);
  const cmds = page.getByTestId("commands-section");
  await cmds.getByTestId("command-add").click();
  const form = cmds.getByTestId("command-form");
  await form.getByLabel("Command name").fill("Engage A side");
  await form.getByLabel("Command category").fill("Bypass");
  await form.getByLabel("CC number").fill("10");
  await form.getByLabel("CC value").fill("127");
  await form.getByLabel("Intent").selectOption("engage");
  await form.getByLabel("Deterministic").selectOption("yes");
  await form.getByLabel("Cited document").selectOption(docId);
  await form.getByLabel("Cited page").fill("2");
  await form.getByLabel(/show first in the scene picker/).check();
  await form.getByTestId("command-save").click();
  const row = cmds.locator("[data-testid^=command-cmd_]").filter({ hasText: "Engage A side" });
  await expect(row).toContainText("CC 10 = 127");
  await expect(row).toContainText("documented");
  await expect(row.getByTestId("command-citation")).toHaveText("Sunset manual p. 2");
  await expect(row.getByRole("button", { name: /favorite Engage A side/i })).toHaveAttribute("aria-pressed", "true");
  // Starter commands from the documented map, keeping its evidence; nothing invented for the user to retype.
  await cmds.getByRole("button", { name: "From documented map" }).click();
  await expect(cmds.locator("[data-testid^=command-cmd_]").filter({ hasText: /^.*Bypass\b/ }).first()).toBeVisible();
  await expect(cmds.locator("[data-testid^=command-cmd_]").filter({ hasText: "Recall program" })).toContainText("PC 0");
  await page.screenshot({ path: "test-results/commands-library.png", fullPage: true }).catch(() => undefined);
  // The engage command equivalent to the derived one was not duplicated.
  const prof = await (await page.request.get(`/api/catalog/devices/${profileId}`)).json();
  const engageCount = prof.midi.commands.filter((c: { cc: number; value: number }) => c.cc === 10 && c.value === 127).length;
  expect(engageCount).toBe(1);
  // A PC command too (added through the API to keep the UI part short).
  prof.midi.commands.push({ id: "cmd_lead", name: "Lead drive", kind: "pc", pc: 4, intent: "recall", deterministic: true, evidence: "user", favorite: true });
  expect((await page.request.put(`/api/catalog/devices/${profileId}/commands`, { data: { commands: prof.midi.commands } })).ok()).toBeTruthy();

  // --- Scene editor: pick it by name.
  await page.goto(`/rigs/${rigId}#scenes`);
  await expect(page.getByRole("tab", { name: "scenes" })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: /^Heavy verse/ }).click();
  await page.getByLabel("Sunset state").selectOption("");
  await page.getByTestId("add-command-inst_sunset").click();
  const picker = page.getByTestId("command-picker");
  await expect(picker).toContainText("channel 3 (instance)");
  // Favorites come first.
  const first = picker.locator("[data-testid^=pick-]").first();
  await expect(first).toContainText("★");
  await picker.locator("[data-testid^=pick-]").filter({ hasText: "Engage A side" }).click();
  await expect(picker.getByTestId("command-preview")).toContainText("CC 10 = 127 on channel 3 → Sunset");
  await expect(picker.getByTestId("command-detail")).toContainText("documented in attached manual, page 2");
  await expect(picker.getByTestId("picker-citation")).toHaveAttribute("href", `/documents/${docId}?page=2`);
  await page.screenshot({ path: "test-results/command-picker.png", fullPage: true }).catch(() => undefined);
  await picker.getByTestId("command-apply").click();
  await expect(picker).toHaveCount(0);
  const applied = page.getByTestId("cc-values-inst_sunset").getByTestId("applied-command");
  await expect(applied).toContainText("“Engage A side”");
  await expect(applied).toHaveAttribute("data-status", "ok");
  const planRow = page.locator("table").last().locator("tr").filter({ hasText: "applies 'Engage A side'" });
  await expect(planRow).toContainText("Sunset");
  await expect(planRow.locator("td").nth(2)).toHaveText("3");
  await expect(planRow.locator("td").nth(4)).toHaveText("10");
  await expect(planRow.locator("td").nth(5)).toHaveText("127");
  // PC command: wire value shown with the device's numbering (Sunset counts from 0).
  await page.getByTestId("add-command-inst_sunset").click();
  await page.getByTestId("pick-cmd_lead").click();
  await expect(page.getByTestId("command-preview")).toContainText("PC 4 on channel 3 → Sunset");
  await expect(page.getByTestId("command-preview")).toContainText("device counts from 0");
  await page.getByTestId("command-apply").click();
  await expect(page.getByLabel("Sunset program")).toHaveValue("4");
  await expect(page.locator("table").last().locator("tr").filter({ hasText: "applies 'Lead drive'" }).locator("td").nth(4)).toHaveText("4");
  await page.screenshot({ path: "test-results/scene-with-commands.png", fullPage: true }).catch(() => undefined);
  await expect(page.getByText("Saved", { exact: true })).toBeVisible({ timeout: 10_000 });

  // --- Reload: nothing lost.
  await page.reload();
  await page.getByRole("button", { name: /^Heavy verse/ }).click();
  await expect(page.getByTestId("cc-values-inst_sunset").getByTestId("applied-command")).toHaveAttribute("data-status", "ok");
  await expect(page.locator("table").last().locator("tr").filter({ hasText: "applies 'Engage A side'" }).locator("td").nth(5)).toHaveText("127");

  // --- The library changes later: the saved scene keeps its bytes and asks for review.
  const latest = await (await page.request.get(`/api/catalog/devices/${profileId}`)).json();
  for (const c of latest.midi.commands) if (c.name === "Engage A side") c.value = 100;
  expect((await page.request.put(`/api/catalog/devices/${profileId}/commands`, { data: { commands: latest.midi.commands } })).ok()).toBeTruthy();
  await page.reload();
  await page.getByRole("button", { name: /^Heavy verse/ }).click();
  const tag = page.getByTestId("cc-values-inst_sunset").getByTestId("applied-command");
  await expect(tag).toHaveAttribute("data-status", "changed");
  await expect(tag).toContainText("definition changed");
  await expect(page.locator("table").last().locator("tr").filter({ hasText: "applies 'Engage A side'" }).locator("td").nth(5)).toHaveText("127");
  await expect(page.getByText(/definition of 'Engage A side' .* changed/)).toBeVisible();
  // Reapplying deliberately is what changes the bytes.
  await tag.getByTestId("reapply-command").click();
  await expect(tag).toHaveAttribute("data-status", "ok");
  await expect(page.locator("table").last().locator("tr").filter({ hasText: "applies 'Engage A side'" }).locator("td").nth(5)).toHaveText("100");
  // Usage is visible from the library side.
  const usage = await (await page.request.get(`/api/catalog/devices/${profileId}/command-usage`)).json();
  const engageId = latest.midi.commands.find((c: { name: string }) => c.name === "Engage A side").id;
  expect(usage[engageId].some((u: { scene_name: string }) => u.scene_name === "Heavy verse")).toBeTruthy();
});

test("commands: an imported profile with no MIDI data takes a command only with an explicit capability statement", async ({ page }) => {
  const id = `e2e-pp-${Date.now().toString(36)}`;
  const body = {
    id, manufacturer: "E2E PP", model: `Mystery ${id}`, category: "effect",
    provenance: { source: "pedalplayground_import", evidence: "third_party" },
    footprint: { width: { value_mm: 70, evidence: "third_party" }, depth: { value_mm: 120, evidence: "third_party" }, height: { value_mm: null, evidence: "unknown" }, includes_jacks: null, display_unit: "mm" },
    declared_unknowns: ["ports (not in dataset)", "midi (not in dataset)"],
  };
  expect((await page.request.post("/api/catalog/devices", { data: body })).ok()).toBeTruthy();
  createdProfiles.push(id);
  await openProfile(page, id);
  const cmds = page.getByTestId("commands-section");
  await expect(cmds.getByTestId("midi-undeclared")).toBeVisible();
  await cmds.getByTestId("command-add").click();
  const form = cmds.getByTestId("command-form");
  await form.getByLabel("Command name").fill("Engage");
  await form.getByLabel("CC number").fill("20");
  await form.getByLabel("CC value").fill("127");
  await expect(form).toContainText("the profile documents no CC map; this number is your statement");
  await form.getByTestId("command-save").click();
  await expect(cmds.locator("[data-testid^=command-cmd_]")).toContainText("user");
  // Declaring the MIDI input is the user's explicit statement, recorded as such.
  page.once("dialog", (d) => d.accept("1"));
  await cmds.getByTestId("declare-midi").click();
  await expect(cmds.getByTestId("midi-undeclared")).toHaveCount(0);
  await expect(page.getByText(/MIDI: din_in/)).toBeVisible();
  const prof = await (await page.request.get(`/api/catalog/devices/${id}`)).json();
  expect(prof.midi.evidence).toBe("user");
  expect(prof.midi.note).toContain("declared by the user");
  expect(prof.midi.cc_map).toEqual([]);
});
